class Form:
    """H = coker P with P positive definite, D lambda_Z(x, y) = lift(x)^T adj(P) lift(y) mod D, and d(Z, t_s + x)."""

    def __init__(self, P):
        self.P, self.n = P, len(P)
        self.D = det_int(P)
        self.adj = [[int(v) for v in row] for row in adjugate_int(P)]
        m, self.cm = m_Q(P)
        self.mods = self.cm.d
        self.lift = {tuple(0 for _ in self.mods): [0] * self.n}
        todo = list(self.lift)
        gens = [(self.cm.coords([int(i == j) for i in range(self.n)]), j) for j in range(self.n)]
        while todo:                       # breadth-first lifts of all elements
            nxt = []
            for x in todo:
                for gx, j in gens:
                    y = self.add(x, gx)
                    if y not in self.lift:
                        v = list(self.lift[x]); v[j] += 1
                        self.lift[y] = v; nxt.append(y)
            todo = nxt
        assert len(self.lift) == self.D
        self.d = {x: -m[self.mul(2, x)] for x in self.lift}   # d(Z, t_s + x)

    def add(self, x, y):
        return tuple((a + b) % q for a, b, q in zip(x, y, self.mods))

    def mul(self, k, x):
        return tuple(k * a % q for a, q in zip(x, self.mods))

    def lam(self, x, y):
        u, v = self.lift[x], self.lift[y]
        return sum(u[i] * sum(self.adj[i][j] * v[j] for j in range(self.n)) for i in range(self.n)) % self.D

    def span(self, gens):
        S = {tuple(0 for _ in self.mods)}
        todo = list(S)
        while todo:
            nxt = []
            for x in todo:
                for g in gens:
                    y = self.add(x, g)
                    if y not in S:
                        S.add(y); nxt.append(y)
            todo = nxt
        return frozenset(S)


def isotropic_subgroups(F, n):
    """All isotropic subgroups of order n."""
    zero = tuple(0 for _ in F.mods)
    cand = [x for x in F.lift if x != zero and F.mul(n, x) == zero and F.lam(x, x) == 0]
    found, seen = set(), set()

    def grow(S, gens):
        if len(S) == n:
            found.add(S); return
        for x in cand:
            if x in S or any(F.lam(x, g) for g in gens):
                continue
            T = F.span(gens + [x])
            if n % len(T) == 0 and T not in seen:
                seen.add(T); grow(T, gens + [x])
    grow(frozenset([zero]), [])
    return found


def passes(F, sign, l, M, g):
    """The Ozsvath-Szabo inequalities on t_s + j g + M for Z0 = sign * Z."""
    x = tuple(0 for _ in F.mods)
    for j in range(l):
        bound = 1 - Fraction((2 * j - l) ** 2, l)
        for m in M:
            if 4 * sign * F.d[F.add(x, m)] < bound:
                return False
        x = F.add(x, g)
    return True


def test(F, signs):
    """First passing configuration (sign, l, |M|) for Z0 = sign * Z, or None."""
    D = F.D
    for sign in signs:
        for n in range(1, D + 1):
            if D % (n * n):
                continue
            l = D // (n * n)
            for M in isotropic_subgroups(F, n):
                gens = sorted(M)
                Pm = [x for x in F.lift if all(F.lam(x, m) == 0 for m in gens)]
                assert len(Pm) == l * n
                done = set()
                for g in Pm:
                    if (sign * F.lam(g, g) - D // l) % D:
                        continue
                    if any(F.mul(l // p, g) in M for p in primes_of(l)):
                        continue
                    coset = frozenset(F.add(g, m) for m in M)
                    if coset in done:
                        continue
                    done.add(coset); done.add(frozenset(F.mul(-1, y) for y in coset))
                    if passes(F, sign, l, M, g):
                        return dict(sign=sign, l=l, M=n)
    return None


def one_montesinos(item):
    name, notation, det_k = item
    sys.path.insert(0, os.path.join(ROOT, 'vendor', 'code', 'lower_bounds', 'montesinos'))
    from montesinos_u1 import plumbing_for, validate_plumbing
    Q, flipped = plumbing_for(notation, det_k)
    if Q is None:
        return name, dict(definite=False)
    validate_plumbing(Q)
    F = Form([[-int(v) for v in row] for row in Q])
    rec = dict(definite=True, det=F.D, flipped=flipped, rank=len(Q), d_spin=str(F.d[tuple(0 for _ in F.mods)]))
    rec['passing'] = test(F, (1, -1))
    rec['obstructed'] = rec['passing'] is None
    return name, rec


def one(item):
    name, pd, s = item
    Gs = goeritz_pair(pd)
    neg = [G for G in Gs if positive_definite([[-v for v in row] for row in G])]
    pos = [G for G in Gs if positive_definite(G)]
    if len(neg) != 1 or len(pos) != 1:
        return name, dict(definite=False)
    F = Form([[-v for v in row] for row in neg[0]])
    F2 = Form(pos[0])                     # bounds -Z
    rec = dict(definite=True, det=F.D, d_spin=str(F.d[tuple(0 for _ in F.mods)]), s=s,
               d_check=sorted(F.d.values()) == sorted(-v for v in F2.d.values()))   # multisets only, not the labels
    rec['passing'] = test(F, (1, -1))
    rec['obstructed'] = rec['passing'] is None
    allowed = {2: (1,), 6: (-1,)}.get(s, (1, -1))
    rec['passing_signed'] = rec['passing'] if rec['passing'] and rec['passing']['sign'] in allowed else test(F, allowed)
    rec['obstructed_signed'] = rec['passing_signed'] is None
    return name, rec


