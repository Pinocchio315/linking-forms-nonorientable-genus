#!/usr/bin/env python
"""The correction-term test of [C] Proposition 2.6 for alternating and Montesinos knots ([C] Proposition 3.1(c),
Theorem D and the controls of Sections 3.5 and 3.7).

Setting ([C] Proposition 2.6 and its proof).  Let F be a smooth Mobius band for K and W = Sigma_2(B^4, F), so
b_2(W) = 1 and H_1(W) is finite of odd order ([T] Lemma 3.3), W is definite and Q_W = (q) with |q| = l.  Let M be the
image of Tors H^2(W) in H^2(Y) = H_1(Y) and P its annihilator.
- M is isotropic, |M|^2 l = det K, and P/M is cyclic of order l.
- P/M is generated by g, the restriction of the dual of the generator of H^2(W)/Tors.  By the subquotient lemma
  ([T] Lemma 3.1: M is isotropic, P = M^perp and P/M = -lambda_{Q_W}), lambda(g, g) = -1/q.  The orthogonal splitting
  of GL Lemma E.1, which fails in general ([T] Example 3.5), is not used.
- The spin^c structures of W whose c_1 is k times that dual modulo torsion (k odd) restrict to the whole coset
  t_s + ((k + l)/2) g + M, and have c_1^2 = k^2 / q.  Here t_s is the spin structure.  (Fixing c_1 itself, torsion
  included, picks one point of the coset; the test runs over the whole coset.)
If Z0 = +-Y bounds the negative-definite W0 = +-W, then lambda_{Z0}(g, g) = 1/l.  The Ozsvath-Szabo inequality
(GL Thm. 12: c_1^2 + b_2 <= 4d for negative-definite fillings) then gives
    4 d(Z0, t_s + j g + m) >= 1 - (2j - l)^2 / l   for 0 <= j < l and every m in M.
test() searches all (Z0, l, M, g).  The knot is obstructed when none passes.  Passing includes the linking-form test
of rank1_linking.py.

d-invariants.  For an alternating diagram, one matrix G of rank1_goeritz.goeritz_pair is negative definite.  X_G is
sharp (Ozsvath-Szabo, branched double covers, Thm. 3.4).  With P = -G and Z = boundary of X_G:
- d(Z, t) = -m_P(t), computed by m_Q of vendor/code/lower_bounds/owens/owens_obstruction.py, which labels t by [xi] in
  coker P (spin = 0), so the label of t_s + x is 2x;
- lambda_Z = P^-1, because X_G is simply connected (Gordon-Litherland, pp. 59-60: the boundary of a 4-manifold with
  H_1 = 0 and intersection matrix A has linking form -A^-1).
The other colouring bounds -Z.  Its d-invariants must be the negatives of these, which is checked (field d_check).
Sign refinement (obstructed_signed): s = sigma + 4 Arf (mod 8) = 2 allows only Z0 = Z and s = 6 only Z0 = -Z.  The
reason: lambda_Z = -G^-1 is isometric to (V + V^T)^-1, whose Witt class is that of <eps/l> with eps = +1 when s = 2
(rank1_linking.py).
Montesinos knots (modes mcontrols, mtargets): Sigma_K or -Sigma_K bounds the negative-definite star plumbing Q of
vendor/code/lower_bounds/montesinos/montesinos_u1.plumbing_for.  It has at most one bad vertex, so the same formula
gives exact d-invariants (Ozsvath-Szabo, plumbed three-manifolds, Thm. 1.2), with P = -Q.  Only the unsigned test is
used.
Modes: controls, the alternating knots with KnotInfo value 1; targets, the alternating knots whose KnotInfo range
starts at 1 and that rank1_linking.py does not obstruct; mcontrols and mtargets, the same for the non-alternating
Montesinos knots, and in mtargets also 11n_38, whose KnotInfo value 2 rests on an argument that [C] Section 3.8
corrects; ls14, the alternating knots with 14 crossings that the table of Lee and Sabloff and rank1_ls14.py leave open;
ls14controls, those with a Mobius band in that table.
Usage: python scripts/rank1_dinv.py controls | targets | mcontrols | mtargets [workers]
       python scripts/rank1_dinv.py ls14 | ls14controls path/to/knot_3-14data.csv [workers]
Output: data/rank1_dinv_<mode>.json
"""
